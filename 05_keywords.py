name = "Tony Stark"

# in last topic we saw that 'find' operation returns the index number of required character in string
# but if we dont want the index number, we just want to check if it exists or not,

# 'in' keyword
print("T" in name)        # True
print("m" in name)        # False
print("Stark" in name)    # True
print("Ironman" in name)  # False