print(5 + 2)      # 7                 addition
print(5 - 2)      # 3                 subtraction
print(5 * 2)      # 10                multiplication
print(5 / 2)      # 2.5               division
print(5 // 2)     # 2                 part after decimal is removed
print(5 % 2)      # 1                 remainder/modulo
print(5 ** 2)     # 25                5 to the power of 2